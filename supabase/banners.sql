create table if not exists public.ms_banners (
  id bigint generated by default as identity primary key,
  image text not null check (char_length(image) <= 500),
  title_ar text not null check (char_length(title_ar) between 1 and 80),
  title_fr text check (char_length(title_fr) <= 80),
  sub_ar text check (char_length(sub_ar) <= 160),
  sub_fr text check (char_length(sub_fr) <= 160),
  cta_ar text check (char_length(cta_ar) <= 30),
  cta_fr text check (char_length(cta_fr) <= 30),
  link text not null default 'shop.html'
    check (char_length(link) <= 300 and (link ~ '^(shop|product|index)\.html' or link ~ '^https://')),
  position text not null default '50% 50%' check (position ~ '^[0-9]{1,3}% [0-9]{1,3}%$'),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.ms_banners enable row level security;

-- الزوار يرون الإعلانات المفعّلة فقط، والمدير يرى الكل
drop policy if exists "ms read banners" on public.ms_banners;
create policy "ms read banners" on public.ms_banners
  for select using (active or public.ms_is_admin());

drop policy if exists "ms admin insert banners" on public.ms_banners;
create policy "ms admin insert banners" on public.ms_banners
  for insert to authenticated with check (public.ms_is_admin());

drop policy if exists "ms admin update banners" on public.ms_banners;
create policy "ms admin update banners" on public.ms_banners
  for update to authenticated using (public.ms_is_admin()) with check (public.ms_is_admin());

drop policy if exists "ms admin delete banners" on public.ms_banners;
create policy "ms admin delete banners" on public.ms_banners
  for delete to authenticated using (public.ms_is_admin());

