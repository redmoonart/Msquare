create table if not exists public.ms_orders (
  id bigint generated always as identity primary key,
  ref text unique check (char_length(ref) <= 24),
  customer_name text not null check (char_length(customer_name) between 2 and 100),
  phone text not null check (char_length(phone) between 8 and 20),
  wilaya text check (char_length(wilaya) <= 60),
  address text check (char_length(address) <= 300),
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) between 1 and 30),
  total integer not null default 0 check (total >= 0),
  notes text check (char_length(notes) <= 500),
  lang text check (lang in ('ar','fr')),
  status text not null default 'new'
    check (status in ('new','confirmed','shipped','delivered','refused','cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists ms_orders_created_at_idx on public.ms_orders (created_at desc);

-- الأسعار والمجموع تُحسب من جدول المنتجات (لا يُوثق بما يرسله المتصفح)
create or replace function public.ms_orders_fill() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  it jsonb;
  p record;
  q integer;
  fixed jsonb := '[]'::jsonb;
  tot integer := 0;
begin
  for it in select value from jsonb_array_elements(new.items) loop
    select id, name, brand, price, stock into p from public.ms_products where id = (it ->> 'id')::bigint;
    if not found or not p.stock then
      raise exception 'product % is not available', it ->> 'id';
    end if;
    q := greatest(1, least(10, coalesce((it ->> 'qty')::integer, 1)));
    fixed := fixed || jsonb_build_object(
      'id', p.id, 'name', p.name, 'brand', p.brand,
      'size', left(coalesce(it ->> 'size', ''), 6),
      'qty', q, 'price', p.price, 'lineTotal', p.price * q);
    tot := tot + p.price * q;
  end loop;
  new.items := fixed;
  new.total := tot;
  new.status := 'new';
  new.created_at := now();
  return new;
end $$;

drop trigger if exists ms_orders_fill on public.ms_orders;
create trigger ms_orders_fill before insert on public.ms_orders
  for each row execute function public.ms_orders_fill();

