create table if not exists public.ms_products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  brand text not null,
  style text not null check (style in ('sport','casual','streetwear','classic','outdoor','sandals')),
  seasons text[] not null default '{}' check (seasons <@ array['spring','summer','autumn','winter']::text[]),
  price integer not null check (price >= 0),
  old_price integer check (old_price >= 0),
  colors text[] not null default array['#111111','#ffffff','#f2f2f2']::text[],
  image text,
  images text[] not null default '{}',
  sizes integer[] not null default array[38,39,40,41,42,43,44,45]::integer[],
  is_new boolean not null default false,
  best boolean not null default false,
  stock boolean not null default true,
  description_ar text,
  description_fr text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.ms_products enable row level security;

drop policy if exists "ms public read products" on public.ms_products;
create policy "ms public read products" on public.ms_products
  for select using (true);

drop policy if exists "ms admin insert products" on public.ms_products;
create policy "ms admin insert products" on public.ms_products
  for insert to authenticated with check (public.ms_is_admin());

drop policy if exists "ms admin update products" on public.ms_products;
create policy "ms admin update products" on public.ms_products
  for update to authenticated using (public.ms_is_admin()) with check (public.ms_is_admin());

drop policy if exists "ms admin delete products" on public.ms_products;
create policy "ms admin delete products" on public.ms_products
  for delete to authenticated using (public.ms_is_admin());

